export function getLocalizedStateName(stateValue?: string, lang?: Language): string {
  if (!stateValue) return "";
  const match = INDIAN_STATES.find(
    (s) => s.id.toLowerCase() === stateValue.toLowerCase() || s.en.toLowerCase() === stateValue.toLowerCase()
  );
  if (!match) return stateValue;
  if (!lang) return match.en;
  return match[lang] || match.en || stateValue;
}